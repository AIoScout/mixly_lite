#ifndef MIXLY_TFLITE_SIGN_PREPROCESS_HPP
#define MIXLY_TFLITE_SIGN_PREPROCESS_HPP

#include <cstdint>

// ── Training-app crop pipeline, baked into the firmware ─────────────────
//
// Mirrors AItraining image_preprocess.py so the deployed model sees the
// same input distribution it was trained on:
//   mode 1 (sign):  dark/lum thresholds segment the sign on the G channel;
//                   the mask drives the search box (bit-identical port of
//                   _focus_bbox / _focus_bbox_adaptive from the P4 firmware
//                   image_provider.cpp, verified against the host), then
//                   PIL-exact bilinear crop-resize + BT.601 luminance +
//                   contrast stretch into the int8 tensor.
//   mode 2 (junction): fixed 40–75 % height band, letterboxed to square.
//   mode 3 (manual):  fixed normalized ROI box.
//   mode 0: off — legacy full-frame behavior (models exported before the
//                   preprocess config existed).
//
// The constants come from model_data.h (g_preprocess_mode / _dark / _lum /
// _roi), generated by the mixly server from the training export's
// preprocess.json. Keep the mode numbering in lockstep with server.js.

namespace TFLiteVision {

struct CropBox {
    int x1, y1, x2, y2;
};

class SignPreprocess {
public:
    // Allocate scratch for frames up to maxSide x maxSide. Prefers PSRAM.
    // Returns false on allocation failure (caller falls back to full-frame).
    bool begin(int maxSide);
    void end();
    bool ready() const { return _scratch != nullptr; }
    int maxSide() const { return _maxSide; }

    // Sign mode: search box for a G-channel (or native grayscale) frame.
    // Tuned thresholds (dark != 0 || lum != 100) mask first, like the host;
    // default thresholds run the exposure-adaptive band search.
    CropBox findSignCrop(const uint8_t* gChannel, int w, int h, int dark, int lum);

    // Fixed crops.
    static CropBox junctionCrop(int w, int h);              // 40–75 % height band
    static CropBox manualCrop(const float roi[4], int w, int h);  // normalized box

    // Crop + PIL-exact bilinear resize + BT.601 luminance -> int8 (gray-128).
    // `rgb` is RGB888 packed (3 bpp). Box may be non-square (junction).
    void cropResizeBilinearRgb(const uint8_t* rgb, int w, int h,
                               const CropBox& box, int outW, int outH,
                               int8_t* out) const;

    // Grayscale-source variant (1 bpp); luminance is the identity.
    void cropResizeBilinearGray(const uint8_t* gray, int w, int h,
                                const CropBox& box, int outW, int outH,
                                int8_t* out) const;

    // Letterbox to square on black (PIL ImageOps.pad-style, centered),
    // used by the junction band. Bilinear source sampling, black outside.
    void cropResizePadBilinearGray(const uint8_t* gray, int w, int h,
                                   const CropBox& box, int outSide,
                                   int8_t* out) const;
    void cropResizePadBilinearRgb(const uint8_t* rgb, int w, int h,
                                  const CropBox& box, int outSide,
                                  int8_t* out) const;

    // Contrast stretch to full [0,255] range when the span is >= 24
    // (mirrors _contrast_stretch_u8 / the firmware contrast_stretch_int8).
    static void contrastStretchInt8(int8_t* img, int n);

private:
    struct Scratch;
    Scratch* _scratch = nullptr;
    int _maxSide = 0;

    CropBox findSearchBoxAdaptive(const uint8_t* grayRaw, int w, int h);
    CropBox findSearchBox(const uint8_t* gray, int w, int h);
};

} // namespace TFLiteVision

#endif
